mode_methods_paragraph <- function(mode) {
  p <- mode$params
  sva_version <- as.character(packageVersion("sva"))
  impute_version <- as.character(packageVersion("impute"))

  scaling_sentence <- switch(p$scale_norm,
    "ParetoNorm" = "Data were subsequently Pareto scaled (mean-centered and divided by the square root of the standard deviation of each feature). ",
    "AutoNorm"   = "Data were subsequently auto scaled (mean-centered and divided by the standard deviation of each feature). ",
    "None"       = "",
    "")

  batch_sentence <- if (isTRUE(p$combat_applied)) {
    paste0("Batch effects were removed using the ComBat empirical Bayes method (sva v", sva_version,
           if (!identical(p$bio_var, "None")) {
             paste0(") with biological group (", html_escape(p$bio_var),
                    ") included as a covariate to preserve biological variation during correction (Johnson et al., 2007). ")
           } else ") (Johnson et al., 2007). ")
  } else if (isTRUE(p$has_batch)) {
    paste0("Principal component analysis showed no batch structure requiring correction, so no batch correction was applied; ",
           "batch (", html_escape(p$batch_var), ") was retained in the metadata so it can be included as a covariate in statistical models. ")
  } else {
    "No batch variable was recorded for this mode, so no batch correction was applied. "
  }

  paste0(
    "Metabolomics data processing was performed using Metabo Tools, a web application developed by the ",
    "University of Florida Southeast Center for Integrated Metabolomics (SECIM; ",
    "<a href='https://secim.ufl.edu/'>https://secim.ufl.edu/</a>). ",
    "For the ", html_escape(mode$label), " mode acquisition, raw peak intensity data from ",
    p$n_samples, " samples and ", p$n_original, " features were imported. ",
    if (p$do_missing_filter) paste0("Features with greater than 50% missing or zero values were removed, retaining ",
                                    p$n_after_missing, " features. ") else "",
    if (p$do_imputation) paste0("Remaining missing and zero values (n = ", p$n_imputed,
                                ") were imputed using k-nearest neighbors (KNN, k = 10) as implemented in the ",
                                "Bioconductor impute package (v", impute_version, "). ") else "",
    if (p$do_iqr_filter) paste0("Low-variance features were removed by filtering the bottom ", p$iqr_threshold,
                                "% by interquartile range, retaining ", p$n_after_iqr, " features. ") else "",
    "Samples were normalized by ", norm_label_for(p$row_norm), " followed by log2 transformation. ",
    batch_sentence, scaling_sentence,
    "The final processed matrix contained ", p$n_final, " features across ", p$n_samples, " samples."
  )
}

mode_step_log_html <- function(mode) {
  p <- mode$params
  paste0(
    '<div class="step-log">',
    '<strong>Input:</strong> ', p$n_original, ' features, ', p$n_samples, ' samples<br>',
    if (p$do_missing_filter) paste0('  &#8594; Missing value filter (&gt;50%): <span class="removed">',
                                    p$n_original - p$n_after_missing, ' features removed</span>, <span class="kept">',
                                    p$n_after_missing, ' retained</span><br>') else '  &#8594; Missing value filter: skipped<br>',
    if (p$do_imputation) paste0('  &#8594; KNN imputation: <span class="kept">', p$n_imputed,
                                ' values imputed</span><br>') else '  &#8594; KNN imputation: skipped<br>',
    if (p$do_iqr_filter) paste0('  &#8594; IQR filter (bottom ', p$iqr_threshold, '%): <span class="removed">',
                                p$n_after_missing - p$n_after_iqr, ' features removed</span>, <span class="kept">',
                                p$n_after_iqr, ' retained</span><br>') else '  &#8594; IQR filter: skipped<br>',
    '  &#8594; Sample normalization: ', norm_label_for(p$row_norm), '<br>',
    '  &#8594; Log2 transformation applied<br>',
    '  &#8594; ',
    if (isTRUE(p$combat_applied)) {
      paste0('ComBat batch correction applied (batch: ', html_escape(p$batch_var), ')')
    } else if (isTRUE(p$has_batch)) {
      '<span class="removed">ComBat batch correction skipped</span>'
    } else {
      'ComBat batch correction not applicable (no batch variable)'
    },
    '<br>',
    '  &#8594; Scaling: ', scale_label_for(p$scale_norm), '<br>',
    '<strong>Output:</strong> ', p$n_final, ' features, ', p$n_samples, ' samples',
    '</div>'
  )
}

mode_file_rows <- function(modes) {
  sheets <- mode_sheet_names(modes)
  paste0(vapply(seq_along(modes), function(i) {
    m <- modes[[i]]; sh <- sheets[[i]]; p <- m$params
    rows <- list(
      c(sh$original, "Raw matched matrix, no processing", "Archive. Start the pipeline over from scratch."),
      c(sh$preprocessed, "After missing value filtering and KNN imputation",
        "Apply your own normalization, transformation and scaling."),
      c(sh$normalized, "After sample normalization and log2 transformation",
        "Apply your own scaling or batch correction method."),
      c(paste0(sh$normalized_scaled, ' <span class="tag tag-secondary">modeling</span>'),
        paste0("Normalized, log2 transformed, scaled (", scale_label_for(p$scale_norm), ")"),
        if (isTRUE(p$has_batch)) {
          "Statistical modeling with batch included as a covariate. Batch effects are present in this matrix — they are controlled for in the model, not removed."
        } else {
          "Statistical modeling. No batch variable was supplied for this mode."
        })
    )
    if (isTRUE(p$combat_applied)) {
      rows[[length(rows) + 1]] <- c(
        paste0(sh$batch_corrected_scaled, ' <span class="tag tag-primary">PCA / clustering</span>'),
        paste0("ComBat corrected and scaled (", scale_label_for(p$scale_norm), ")"),
        "PCA, clustering and heatmaps. Do not also include batch as a covariate when using this matrix.")
    }
    rows[[length(rows) + 1]] <- c(sh$metadata, "Sample metadata for this mode",
                                  "Model design, including the batch column where one was supplied.")
    paste0(
      '<tr><td colspan="3" style="background:#eaf4fb;"><strong>', html_escape(m$label), ' mode</strong></td></tr>',
      paste0(vapply(rows, function(r) {
        paste0('<tr><td class="filename">', r[1], '</td><td>', r[2], '</td><td>', r[3], '</td></tr>')
      }, character(1)), collapse = "")
    )
  }, character(1)), collapse = "")
}

generate_html_report <- function(modes, de_runs = list(), output_path) {
  de_runs <- if (is.null(de_runs)) list() else de_runs
  modes <- if (is.null(modes)) list() else modes

  any_combat <- any(vapply(modes, function(m) isTRUE(m$params$combat_applied), logical(1)))
  any_batch <- any(vapply(modes, function(m) isTRUE(m$params$has_batch), logical(1)))

  de_file_rows <- if (length(de_runs) > 0) {
    paste0(
      '<tr><td colspan="3" style="background:#eaf4fb;"><strong>Differential analysis</strong></td></tr>',
      paste0(vapply(seq_along(de_runs), function(i) {
        run <- de_runs[[i]]
        paste0(
          '<tr><td class="filename">', html_escape(de_sheet_name(run, i)),
          ' <span class="tag tag-secondary">results</span></td>',
          '<td>', if (run$mode == "pairwise") "Moderated t-test" else "Moderated F-test",
          ' results for ', html_escape(run$label), '</td>',
          '<td>Per-feature statistics with fold changes, p-values and BH-adjusted FDR. ',
          run$n_sig, ' of ', run$n_features, ' features were significant.</td></tr>')
      }, character(1)), collapse = ""))
  } else ""

  meta_block <- paste0(
    '<div class="meta">',
    '<strong>Generated:</strong> ', format(Sys.time(), "%Y-%m-%d %H:%M:%S"), '<br>',
    '<strong>Ionization modes:</strong> ',
    paste(vapply(modes, function(m) html_escape(m$label), character(1)), collapse = ", "), '<br>',
    paste0(vapply(modes, function(m) {
      paste0('<strong>', html_escape(m$label), ':</strong> ', m$params$n_samples, ' samples, ',
             m$params$n_original, ' features in, ', m$params$n_final, ' out; ',
             if (isTRUE(m$params$combat_applied)) 'ComBat applied' else if (isTRUE(m$params$has_batch)) 'ComBat skipped' else 'no batch variable',
             '; ', scale_label_for(m$params$scale_norm), '<br>')
    }, character(1)), collapse = ""),
    if (length(de_runs) > 0) paste0('<strong>Differential comparisons:</strong> ', length(de_runs), '<br>') else "",
    '</div>')

  methods_block <- paste0(
    '<h2>Methods Paragraph</h2><div class="methods">',
    paste0(vapply(modes, function(m) paste0('<p>', mode_methods_paragraph(m), '</p>'), character(1)), collapse = ""),
    if (any_combat) paste0(
      '<p><strong>Reference:</strong> Johnson WE, Li C, Rabinovic A. ',
      'Adjusting batch effects in microarray expression data using empirical Bayes methods. ',
      '<em>Biostatistics</em>. 2007;8(1):118-127. doi:10.1093/biostatistics/kxj037</p>') else "",
    '<p style="font-size:12px; color:#888; margin-top:10px;">',
    'This paragraph is provided as a draft for your methods section. Please review and adjust as needed for your specific analysis context.',
    '</p></div>')

  processing_block <- paste0(
    '<h2>Processing Steps</h2>',
    paste0(vapply(modes, function(m) {
      paste0('<h3>', html_escape(m$label), ' mode</h3>', mode_step_log_html(m))
    }, character(1)), collapse = ""))

  pca_block <- paste0(
    '<h2>PCA Plots</h2>',
    '<p>PCA is shown per mode, since the modes are separate acquisitions on different intensity scales. Points are colored by biological group and by batch to show whether batch structure is present and, where ComBat was applied, whether it was removed while biological signal was preserved.</p>',
    paste0(vapply(modes, function(m) {
      section <- paste0('<h3>', html_escape(m$label), ' mode</h3>')
      if (!is.null(m$pca_before)) {
        section <- paste0(section, '<h4>Before batch correction</h4>',
                          embed_plotly(create_pca_plots(m$pca_before,
                                                        paste0(m$label, " — before batch correction")), "450px"))
      } else {
        section <- paste0(section, '<p><em>PCA was not run for this mode.</em></p>')
      }
      if (!is.null(m$pca_after)) {
        section <- paste0(section, '<h4>After batch correction and scaling</h4>',
                          embed_plotly(create_pca_plots(m$pca_after,
                                                        paste0(m$label, " — after batch correction and scaling")), "450px"))
      } else if (isTRUE(m$params$has_batch)) {
        section <- paste0(section,
                          '<p><em>ComBat was not applied to this mode, so there is no post-correction PCA.</em></p>')
      }
      section
    }, character(1)), collapse = ""))

  de_block <- if (length(de_runs) > 0) {
    paste0(vapply(seq_along(de_runs), function(i) de_report_section(de_runs[[i]], i), character(1)), collapse = "")
  } else ""

  batch_warning <- if (any_batch) {
    paste0(
      '<div class="warning"><strong>Note on batch correction and statistical modeling:</strong> ',
      'These two approaches are mutually exclusive. If you use a <code>data_batch_corrected_scaled</code> matrix, ',
      'do not include batch as a covariate in your model. If you use <code>data_normalized_scaled</code>, ',
