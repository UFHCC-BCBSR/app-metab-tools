generate_readme <- function(modes, de_runs = list()) {
  rows <- list(data.frame(
    Section = c("ABOUT THIS FILE", "ABOUT THIS FILE"),
    Detail = c(
      paste("Generated by Metabo Tools on", format(Sys.time(), "%Y-%m-%d %H:%M:%S")),
      paste0("This file contains all processed versions of your data",
             if (length(modes) > 1) paste0(" for ", length(modes),
                                           " ionization modes, each processed separately") else "",
             ". See each sheet description below to understand which to use for your analysis.")
    ), stringsAsFactors = FALSE))

  sheets <- mode_sheet_names(modes)

  for (i in seq_along(modes)) {
    m <- modes[[i]]
    p <- m$params
    sh <- sheets[[i]]
    mode_tag <- paste0("MODE: ", m$label)

    steps <- c(
      "Step 1: Sample matching — feature matrix columns matched to metadata sample names",
      if (p$do_missing_filter) "Step 2: Missing value filter — features with >50% missing values removed" else "Step 2: Missing value filter — skipped",
      if (p$do_imputation) "Step 3: KNN imputation — remaining missing/zero values imputed" else "Step 3: KNN imputation — skipped",
      if (p$do_iqr_filter) paste0("Step 4: IQR filter — bottom ", p$iqr_threshold, "% lowest variance features removed") else "Step 4: IQR filter — skipped",
      paste("Step 5: Sample normalization —", p$row_norm),
      "Step 6: Log2 transformation",
      if (isTRUE(p$combat_applied)) {
        paste0("Step 7: Batch correction — ComBat (batch variable: ", p$batch_var,
               "; biological variable: ", p$bio_var, ")")
      } else if (isTRUE(p$has_batch)) {
        "Step 7: Batch correction — skipped (batch variable present but ComBat not applied)"
      } else {
        "Step 7: Batch correction — not applicable (no batch variable)"
      },
      paste("Step 8: Scaling —", p$scale_norm)
    )
    rows[[length(rows) + 1]] <- data.frame(
      Section = rep(paste0(mode_tag, " — PIPELINE"), length(steps)),
      Detail = steps, stringsAsFactors = FALSE)

    sheet_rows <- list(
      c(sh$original, "Raw matched matrix with no processing applied. Use this to start the pipeline over from scratch."),
      c(sh$preprocessed, "After missing value filtering and KNN imputation, nothing else applied. Use this to apply your own normalization, transformation and scaling."),
      c(sh$normalized, "After sample normalization and log2 transformation. Use this to apply your own scaling or batch correction method."),
      c(sh$normalized_scaled, paste0(
        "Sample normalized, log2 transformed and scaled (", p$scale_norm, "). ",
        if (isTRUE(p$has_batch)) {
          "Batch effects are still present in this matrix — include the batch column from the metadata sheet as a covariate in your model. "
        } else {
          "No batch variable was supplied for this mode. "
        },
        "Use for statistical modeling."))
    )
    if (isTRUE(p$combat_applied)) {
      sheet_rows[[length(sheet_rows) + 1]] <- c(sh$batch_corrected_scaled, paste0(
        "ComBat batch corrected and scaled (", p$scale_norm, "). ",
        "Use for PCA, clustering and heatmaps. Do not also include batch as a covariate in your model when using this matrix."))
    }
    sheet_rows[[length(sheet_rows) + 1]] <- c(sh$metadata,
      "Full sample metadata for this mode, including the batch column where one was supplied.")

    rows[[length(rows) + 1]] <- data.frame(
      Section = vapply(sheet_rows, function(r) paste0("SHEET: ", r[1]), character(1)),
      Detail = vapply(sheet_rows, function(r) r[2], character(1)),
      stringsAsFactors = FALSE)

    log_rows <- c(
      paste("Features in raw matched matrix:", p$n_original),
      if (p$do_missing_filter) paste("Features after missing value filter:", p$n_after_missing) else "Missing value filter: not applied",
      if (p$do_imputation) paste("Missing/zero values imputed:", p$n_imputed) else "KNN imputation: not applied",
      if (p$do_iqr_filter) paste("Features after IQR filter:", p$n_after_iqr) else "IQR filter: not applied",
      paste("Features in final matrix:", p$n_final),
      paste("Samples matched:", p$n_samples)
    )
    rows[[length(rows) + 1]] <- data.frame(
      Section = rep(paste0(mode_tag, " — PROCESSING LOG"), length(log_rows)),
      Detail = log_rows, stringsAsFactors = FALSE)
  }

  de_rows <- de_readme_rows(de_runs)
  if (!is.null(de_rows)) rows[[length(rows) + 1]] <- de_rows

  do.call(rbind, rows)
}

# ---------------------------
# Excel package
# ---------------------------
build_excel_package <- function(modes, de_runs, file) {
  mat_to_df <- function(mat) tibble::rownames_to_column(as.data.frame(mat), var = "feature")
  sheets <- mode_sheet_names(modes)

  wb <- createWorkbook()
  addWorksheet(wb, "README")
  writeData(wb, "README", generate_readme(modes, de_runs))

  for (i in seq_along(modes)) {
    m <- modes[[i]]
    sh <- sheets[[i]]
    add <- function(name, data) {
      addWorksheet(wb, name)
      writeData(wb, name, data)
    }
    add(sh$original, mat_to_df(m$matched_data$count_matrix))
    add(sh$preprocessed, mat_to_df(m$preprocessed))
    add(sh$normalized, mat_to_df(m$normalized))
    if (!is.null(m$normalized_scaled)) add(sh$normalized_scaled, mat_to_df(m$normalized_scaled))
    if (!is.null(m$batch_corrected_scaled)) {
      add(sh$batch_corrected_scaled, mat_to_df(m$batch_corrected_scaled))
    }
    add(sh$metadata, m$matched_data$full_sample_data)
  }

  for (sheet in de_excel_sheets(de_runs)) {
    addWorksheet(wb, sheet$name)
    writeData(wb, sheet$name, sheet$data)
  }

  headerStyle <- createStyle(textDecoration = "bold", fgFill = "#2980b9",
                             fontColour = "white", wrapText = TRUE)
  addStyle(wb, "README", headerStyle, rows = 1, cols = 1:2, gridExpand = TRUE)
  setColWidths(wb, "README", cols = 1:2, widths = c(35, 90))

  saveWorkbook(wb, file, overwrite = TRUE)
}

