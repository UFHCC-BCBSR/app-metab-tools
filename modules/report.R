# ===========================
# Processing report, README and Excel package
# ===========================
# Covers every ionization mode processed in the session plus any differential
# analysis comparisons. Each mode is reported on its own — separate processing
# log, separate PCA, separate methods sentence — because each was processed on
# its own. Only the differential analysis sections combine modes.

# Short, stable prefix for a mode's Excel sheets. With a single mode the sheets
# keep their original unprefixed names.
mode_prefix <- function(label) {
  clean <- gsub("[^A-Za-z0-9]", "", label)
  if (!nzchar(clean)) return("M")
  toupper(substr(clean, 1, 3))
}

mode_sheet_names <- function(modes) {
  prefixed <- length(modes) > 1
  lapply(seq_along(modes), function(i) {
    p <- if (prefixed) paste0(mode_prefix(modes[[i]]$label), "_") else ""
    list(
      original = paste0(p, "data_original"),
      preprocessed = paste0(p, "data_preprocessed"),
      normalized = paste0(p, "data_normalized"),
      normalized_scaled = paste0(p, "data_normalized_scaled"),
      batch_corrected_scaled = paste0(p, "data_batch_corrected_scaled"),
      metadata = paste0(p, "metadata")
    )
  })
}

scale_label_for <- function(scale_norm) {
  switch(scale_norm,
         "ParetoNorm" = "Pareto scaling",
         "AutoNorm" = "Auto scaling (mean-centering and division by standard deviation)",
         "None" = "no scaling",
         scale_norm)
}

norm_label_for <- function(row_norm) {
  switch(row_norm,
         "SumNorm" = "sum normalization",
         "MedianNorm" = "median normalization",
         "None" = "no sample normalization",
         row_norm)
}

